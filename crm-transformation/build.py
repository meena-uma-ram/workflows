#!/usr/bin/env python3
"""Generate README.md, workflow.json and index.html from src/model.py.

Usage: python3 build.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "src"))
import model  # noqa: E402

SHAPES = {"step": '["{}"]', "decision": '{{"{}"}}', "terminal": '(["{}"])', "system": '[("{}")]', "group": '[["{}"]]'}


def edges_of(w):
    for e in w["edges"]:
        frm, to, label = (e + ("",))[:3]
        loop = label.startswith("~")
        yield frm, to, label.lstrip("~").strip(), loop


def validate():
    tables = {t["id"] for t in model.TABLES}
    errors = []
    for w in model.WORKFLOWS:
        ids = [n["id"] for n in w["nodes"]]
        if len(ids) != len(set(ids)):
            errors.append(f"{w['id']}: duplicate node ids")
        for frm, to, _, _ in edges_of(w):
            for x in (frm, to):
                if x not in ids:
                    errors.append(f"{w['id']}: edge references unknown node {x}")
        for n in w["nodes"]:
            if n.get("ref") and n["ref"] not in tables:
                errors.append(f"{w['id']}.{n['id']}: unknown ref {n['ref']}")
            if n.get("status", "established") not in model.STATUS:
                errors.append(f"{w['id']}.{n['id']}: unknown status")
    if errors:
        sys.exit("\n".join(errors))


def to_json():
    out = {"programme": model.PROGRAMME,
           "status": {k: {"label": v[0], "meaning": v[1]} for k, v in model.STATUS.items()},
           "workflows": [], "tables": model.TABLES}
    for w in model.WORKFLOWS:
        nodes = [{"id": f"{w['id']}.{n['id']}", **{k: v for k, v in n.items() if k != "id"}} for n in w["nodes"]]
        edges = []
        for frm, to, label, loop in edges_of(w):
            e = {"from": f"{w['id']}.{frm}", "to": f"{w['id']}.{to}"}
            if label:
                e["label"] = label
            if loop:
                e["style"] = "loop"
            edges.append(e)
        out["workflows"].append({k: w[k] for k in ("id", "group", "name", "principle", "intro", "direction")}
                                | {"nodes": nodes, "edges": edges})
    return out


def q(s):
    return s.replace('"', "#quot;")


def mermaid(w):
    lines = [f"flowchart {w['direction']}"]
    for n in w["nodes"]:
        text = q(n["label"])
        if n["type"] == "group" and n.get("items"):
            text += "<br/>" + "<br/>".join("· " + q(i) for i in n["items"])
        if n.get("owner"):
            text += "<br/><i>" + q(n["owner"]) + "</i>"
        lines.append(f"    {n['id']}" + SHAPES[n["type"]].format(text))
    for frm, to, label, loop in edges_of(w):
        if loop:
            arrow = f"-. \"{q(label)}\" .->" if label else "-.->"
        else:
            arrow = f"-- \"{q(label)}\" -->" if label else "-->"
        lines.append(f"    {frm} {arrow} {to}")
    lines += ["    classDef decision fill:#fbf0dc,stroke:#a8650b,color:#18222d;",
              "    classDef exit fill:#eef1f3,stroke:#7c8792,color:#4a5560;",
              "    classDef post fill:#e2f2e8,stroke:#2f7d4f,color:#18222d;",
              "    classDef escalation fill:#fbe7e4,stroke:#b4442f,color:#18222d;",
              "    classDef proposed stroke:#5b4bc4,stroke-width:2px,stroke-dasharray:6 3;",
              "    classDef validate stroke:#b4442f,stroke-width:2px,stroke-dasharray:2 3;"]
    for cls in ("decision", "exit", "post", "escalation", "proposed", "validate"):
        members = [n["id"] for n in w["nodes"]
                   if (cls == "decision" and n["type"] == "decision") or n.get("kind") == cls or n.get("status") == cls]
        if members:
            lines.append(f"    class {','.join(members)} {cls};")
    return "\n".join(lines)


def md_table(t):
    head = "| " + " | ".join(t["cols"]) + " |\n| " + " | ".join("---" for _ in t["cols"]) + " |\n"
    body = "".join("| " + " | ".join(c.replace("|", "\\|") for c in r) + " |\n" for r in t["rows"])
    return head + body


def slug(s):
    return "".join(c for c in s.lower().replace(" ", "-") if c.isalnum() or c == "-")


def readme():
    p = model.PROGRAMME
    out = [f"# {p['name']}: {p['tagline'].lower()}", "",
           "<!-- Generated by build.py from src/model.py. Edit the model, then run `python3 build.py`. -->", "",
           f"**Goal:** {p['goal']}", "",
           "| " + " | ".join(k for k, _ in p["facts"]) + " |",
           "| " + " | ".join("---" for _ in p["facts"]) + " |",
           "| " + " | ".join(v for _, v in p["facts"]) + " |", "",
           f"**Primary objective:** {p['primary_objective']}", "",
           f"**Supporting objectives:** {p['supporting_objectives']}", "",
           "## How to use this", "",
           "- **[`index.html`](index.html)** is the interactive map: every workflow as a node graph, with owners, required "
           "information, walk-through, search, reference tables and per-node progress tracking. Download it and open it in a browser.",
           "- **[`workflow.json`](workflow.json)** has the same nodes, edges and tables in machine-readable form.",
           "- **[`src/model.py`](src/model.py)** is the single source. Edit it and run `python3 build.py` to regenerate all three files.",
           "", "### Decision status", "",
           "| Marker | Status | Meaning |", "| --- | --- | --- |",
           "| solid outline | Established | " + model.STATUS["established"][1] + " |",
           "| dashed violet outline | Proposed | " + model.STATUS["proposed"][1] + " |",
           "| dotted red outline | Validate in Month 1 | " + model.STATUS["validate"][1] + " |",
           "", "## Workflows", ""]
    group = None
    for w in model.WORKFLOWS:
        if w["group"] != group:
            group = w["group"]
            out.append(f"**{group}**")
            out.append("")
        out.append(f"- [{w['id']}. {w['name']}](#{slug(w['id'] + '-' + w['name'])}) ({w['principle']})")
    out += ["", "**Reference tables**", ""]
    out += [f"- [{t['title']}](#{slug(t['title'])})" for t in model.TABLES]
    out.append("")
    for w in model.WORKFLOWS:
        out += ["---", "", f"## {w['id']}. {w['name']}", "", f"*{w['principle']}.* {w['intro']}", "",
                "```mermaid", mermaid(w), "```", ""]
    out += ["---", "", "# Reference tables", ""]
    for t in model.TABLES:
        flag = f" *({model.STATUS[t['status']][0]})*" if t.get("status") else ""
        out += [f"## {t['title']}", "", f"*{t['section']}.*{flag} {t['note']}", "", md_table(t)]
    return "\n".join(out)


def html(data):
    tpl = open(os.path.join(HERE, "src", "template.html"), encoding="utf-8").read()
    payload = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    body = tpl.replace("/*DATA*/", payload)
    page = ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
            '<style>body{margin:0}[hidden]{display:none!important}</style>\n</head>\n<body>\n'
            + body + "\n</body>\n</html>\n")
    return body, page


def main():
    validate()
    data = to_json()
    with open(os.path.join(HERE, "workflow.json"), "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")
    with open(os.path.join(HERE, "README.md"), "w", encoding="utf-8") as f:
        f.write(readme())
    body, page = html(data)
    with open(os.path.join(HERE, "index.html"), "w", encoding="utf-8") as f:
        f.write(page)
    if len(sys.argv) > 1:  # optional: also write the skeleton-less page body for hosting elsewhere
        with open(sys.argv[1], "w", encoding="utf-8") as f:
            f.write(body)
    print(f"{len(model.WORKFLOWS)} workflows, "
          f"{sum(len(w['nodes']) for w in model.WORKFLOWS)} nodes, {len(model.TABLES)} tables")


if __name__ == "__main__":
    main()
